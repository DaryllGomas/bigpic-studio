import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
const out = process.env.OUT_DIR;
await mkdir(out, { recursive: true });
const assert = (ok, message) => { if (!ok) throw Error(message); };
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM, args: ['--use-gl=angle','--enable-gpu','--ignore-gpu-blocklist','--use-angle=vulkan'] });
const results = [];
for (const width of [1920,1366,820,390]) {
  const page = await browser.newPage({ viewport: {width, height:1080}, reducedMotion:'reduce' });
  const errors=[], consoleErrors=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('console', m=>{if(m.type()==='error') consoleErrors.push(m.text());});
  await page.goto(process.env.SITE_URL, {waitUntil:'networkidle'});
  const button=page.locator('[data-whatsnew]');
  await button.waitFor({state:'visible'});
  await page.waitForTimeout(500);
  assert(await button.getAttribute('data-track')==='hero-whats-new', 'Analytics missing');
  const dates=await page.locator('#wnModal time').evaluateAll(ts=>ts.map(t=>t.dateTime).sort());
  assert(await button.locator('time').getAttribute('datetime')===dates.at(-1), 'Wrong newest date');
  assert(await button.evaluate(b=>b.classList.contains('has-unread')), 'Unread missing');
  const play=await page.locator('[data-track="hero-the-path"]').boundingBox();
  const news=await button.boundingBox();
  assert(Math.abs(play.height-news.height)<1,'Unequal heights');
  if(width>390) assert(Math.abs(play.y-news.y)<1,'Buttons not beside each other');
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth), 'Page overflow');
  await page.locator('.hero2').screenshot({path:`${out}/${width}-hero.png`});
  await button.focus();
  assert(await button.evaluate(b=>getComputedStyle(b).outlineStyle)==='solid','Focus outline missing');
  await page.keyboard.press('Enter');
  assert(await page.locator('#wnModal').evaluate(m=>m.classList.contains('open')),'Modal did not open');
  assert(await page.locator('[data-wn-close]').first().evaluate(b=>b===document.activeElement),'Close not focused');
  await page.keyboard.press('Shift+Tab');
  assert(await page.locator('.wn-all').evaluate(b=>b===document.activeElement),'Focus escaped modal');
  await page.locator('#wnModal').screenshot({path:`${out}/${width}-modal.png`});
  await page.keyboard.press('Escape');
  assert(await button.evaluate(b=>b===document.activeElement),'Focus not restored');
  await page.reload({waitUntil:'networkidle'});
  assert(!await button.evaluate(b=>b.classList.contains('has-unread')),'Seen state not persisted');
  await page.addInitScript(()=>{Storage.prototype.getItem=()=>{throw Error('Storage blocked');};Storage.prototype.setItem=()=>{throw Error('Storage blocked');};});
  await page.reload({waitUntil:'networkidle'});
  await button.click();
  assert(await page.locator('#wnModal').evaluate(m=>m.classList.contains('open')),'Blocked storage broke modal');
  results.push({width,play,news,errors,consoleErrors});
  await page.close();
}
await writeFile(`${out}/results.json`,JSON.stringify(results,null,2));
await browser.close();
assert(results.every(r=>r.errors.length===0),'Page errors');
